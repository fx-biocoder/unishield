const { describe, it } = require('node:test');
const assert = require('node:assert');
const { createExtensionContext } = require('./helpers');

describe('UniShield.Defaults and Pattern Registries', () => {
  const { ctx } = createExtensionContext();
  const Defaults = ctx.UniShield.Defaults;

  it('exposes well-formed platform defaults', () => {
    assert.strictEqual(Defaults.global.enabled, true);

    // Reddit defaults
    assert.strictEqual(Defaults.reddit.enabled, true);
    assert.strictEqual(Defaults.reddit.detectBotPatterns, true);
    assert.strictEqual(Defaults.reddit.removeEditorializedTitles, true);
    assert.ok(Array.isArray(Defaults.reddit.subredditBlocklist));

    // X defaults
    assert.strictEqual(Defaults.x.enabled, true);
    assert.strictEqual(Defaults.x.politicalStrictness, 0);
    assert.strictEqual(Defaults.x.removeBroetryPosts, true);

    // LinkedIn defaults
    assert.strictEqual(Defaults.linkedin.enabled, true);
    assert.strictEqual(Defaults.linkedin.removePromotedPosts, true);
    assert.strictEqual(Defaults.linkedin.removeBroetryPosts, true);
  });

  it('detects AI pattern markers', () => {
    const aiPatterns = Defaults.patterns.ai;
    assert.ok(aiPatterns.length > 0);

    const testMatch = (str) => aiPatterns.some(p => p.test(str));
    assert.strictEqual(testMatch('Generated by AI using GPT-4 model'), true);
    assert.strictEqual(testMatch('Drop a comment below and share your thoughts!'), true);
    assert.strictEqual(testMatch('Comenta debajo qué opinas'), true);
    assert.strictEqual(testMatch('Totally normal sentence with no triggers'), false);
  });

  it('detects Crypto spam markers', () => {
    const cryptoPatterns = Defaults.patterns.crypto;
    const testMatch = (str) => cryptoPatterns.some(p => p.test(str));
    assert.strictEqual(testMatch('Minting free NFT solana whitelist now!'), true);
    assert.strictEqual(testMatch('Buy Bitcoin btc now guaranteed 10x profit'), true);
    assert.strictEqual(testMatch('Just had coffee this morning'), false);
  });

  it('detects LinkedIn corporate clutter keywords', () => {
    const liPatterns = Defaults.linkedinPatterns;
    assert.ok(liPatterns.promotedWords.includes('Promoted'));
    assert.ok(liPatterns.promotedWords.includes('Promocionado'));
    assert.ok(liPatterns.suggestedWords.includes('Suggested'));
    assert.ok(liPatterns.suggestedWords.includes('Sugerido'));
    assert.ok(liPatterns.broetryRegex.test('Do you agree?'));
    assert.ok(liPatterns.broetryRegex.test('¿Estás de acuerdo?'));
  });
});
